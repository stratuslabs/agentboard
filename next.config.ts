import type { NextConfig } from "next";

// Baseline hardening headers. A full Content-Security-Policy is deliberately
// left out for now — it needs a nonce pipeline to work with Next's inline
// bootstrap scripts — but `frame-ancestors` is safe to ship on its own and is
// the directive modern browsers honour over `X-Frame-Options`.
const securityHeaders = [
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
